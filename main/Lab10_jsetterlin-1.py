from pathlib import Path
from word_analyzer import WordAnalyzer

def main():
    """Used to run the main logic of the program."""
    while True:
        file_paths = {"1": Path.cwd() / "textfiles" / "monte_cristo.txt",
                    "2": Path.cwd() / "textfiles" / "princess_mars.txt",
                    "3": Path.cwd() / "textfiles" / "Tarzan.txt",
                    "4": Path.cwd() / "textfiles" / "treasure_island.txt"}

        print("Select a file to analyze:")
        print("1. Monte Cristo")
        print("2. Princess Mars")
        print("3. Tarzan")
        print("4. Treasure Island")
        print("5. Exit")
        
        user_choice = input("Enter the number of your choice: ")

        if user_choice == "5":
            quit()

        if user_choice not in file_paths:
            print("Please select a valid file.")
            continue

        word_analyzer = WordAnalyzer(file_paths[user_choice])
        if word_analyzer.process_file():
            word_analyzer.print_report()

main()