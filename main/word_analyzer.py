from pathlib import Path
import string

class WordAnalyzer:
    """
    Used to create WordAnalyzer objects.
    """

    def __init__(self, filepath):
        """Used to initialize WordAnalyzer objects."""
        self.filepath = filepath
        #word_frequency is an empty dictionary.
        self.word_frequnecy = {}

    def process_file(self):
        """
        Used to hold the main logic of processing files.
        """


        translation_table = str.maketrans("", "", string.punctuation + "”" + "“" + "‘" + "’" + "•")
        no_punctuation = self.filepath.read_text(encoding="utf-8-sig").translate(translation_table)
        no_punctuation = no_punctuation.lower()

        # The below line of code is recieved from Claude sonnet 5.5.
        # The split() method takes a string and puts each word into a list.
        word_list = no_punctuation.split()

        for word in word_list:
            if word in self.word_frequnecy:
                self.word_frequnecy[word] += 1
            else:
                self.word_frequnecy[word] = 1